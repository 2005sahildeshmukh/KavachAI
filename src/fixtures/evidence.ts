export function variantsFor(hazard: Hazard): Evidence[] {
  return FIXTURES.filter((f) => f.hazard === hazard);
}

export function getEvidence(hazard: Hazard, variant: Variant): Evidence {
  const found = FIXTURES.find((f) => f.hazard === hazard && f.variant === variant);
  if (!found) throw new Error(`No fixture for ${hazard}/${variant}`);
  return found;
}
